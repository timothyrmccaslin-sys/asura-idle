#!/usr/bin/env python3
"""Asura soundtrack: original lo-fi / boom-bap hip hop loops, synthesised from
scratch with numpy (no samples, no third-party audio). Every sound here -- drums,
bass, electric piano, koto (Karplus-Strong), shakuhachi, taiko, vinyl dust -- is
generated by this script, so the output belongs to the project.

  python3 tools/music.py OUTDIR      -> OUTDIR/{ink-road,willow-rain,oni-drums}.wav + loops.json

Each track is rendered as an exact-length circular loop (note and reverb tails
wrap around to the start), then written with PAD seconds of wrap-around audio on
both ends so the player can loop sample-accurately regardless of codec padding.
"""
import json, sys, os
import numpy as np
from scipy.signal import butter, sosfilt, fftconvolve

SR = 44100
PAD = 0.5
rng = np.random.default_rng(7)

def hz(n):  # midi -> Hz
    return 440.0 * 2 ** ((n - 69) / 12)

def env_exp(n, k):
    t = np.arange(n) / SR
    return np.exp(-t * k)

def bp(x, lo, hi, order=2):
    return sosfilt(butter(order, [lo, hi], btype='band', fs=SR, output='sos'), x)

def lp(x, f, order=2):
    return sosfilt(butter(order, f, btype='low', fs=SR, output='sos'), x)

def hp(x, f, order=2):
    return sosfilt(butter(order, f, btype='high', fs=SR, output='sos'), x)

def fade(x, a=0.004, r=0.03):
    n = len(x); x = x.copy()
    na, nr = min(n, int(a * SR)), min(n, int(r * SR))
    if na: x[:na] *= np.linspace(0, 1, na)
    if nr: x[-nr:] *= np.linspace(1, 0, nr)
    return x

# ---------------------------------------------------------------- drums
def kick(v=1.0, hard=False):
    n = int(0.55 * SR); t = np.arange(n) / SR
    f = 46 + (95 if hard else 80) * np.exp(-t * 30)
    x = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * (5.5 if hard else 7))
    x[:220] += rng.normal(0, 0.35, 220) * np.linspace(1, 0, 220)
    return np.tanh(x * (2.6 if hard else 1.8)) * 0.9 * v

def snare(v=1.0):
    n = int(0.4 * SR); t = np.arange(n) / SR
    nz = bp(rng.normal(0, 1, n), 1200, 7000) * np.exp(-t * 17)
    tone = np.sin(2 * np.pi * 182 * t) * np.exp(-t * 28) * 0.7
    body = bp(rng.normal(0, 1, n), 300, 900) * np.exp(-t * 30) * 0.6
    return np.tanh((nz * 1.2 + tone + body) * 1.4) * 0.55 * v

def rim(v=1.0):
    n = int(0.12 * SR); t = np.arange(n) / SR
    return (bp(rng.normal(0, 1, n), 1800, 4500) * np.exp(-t * 70) + np.sin(2 * np.pi * 820 * t) * np.exp(-t * 90)) * 0.35 * v

def hat(v=1.0, open_=False):
    n = int((0.35 if open_ else 0.07) * SR); t = np.arange(n) / SR
    return hp(rng.normal(0, 1, n), 7000, 4) * np.exp(-t * (11 if open_ else 75)) * 0.22 * v

def taiko(v=1.0, f0=62):
    n = int(1.4 * SR); t = np.arange(n) / SR
    f = f0 + 30 * np.exp(-t * 18)
    x = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 3.6)
    skin = lp(rng.normal(0, 1, n), 600) * np.exp(-t * 14) * 0.8
    slap = bp(rng.normal(0, 1, n), 900, 3500) * np.exp(-t * 60) * 0.5
    return np.tanh((x + skin + slap) * 1.6) * 0.8 * v

# ---------------------------------------------------------------- tonal
def bass(note, dur, v=1.0, grit=0.0):
    n = int((dur + 0.05) * SR); t = np.arange(n) / SR
    f = hz(note)
    x = np.sin(2 * np.pi * f * t) + 0.25 * np.sin(4 * np.pi * f * t) + 0.08 * np.sin(6 * np.pi * f * t)
    e = np.minimum(1, t / 0.006) * np.exp(-t * 1.1)
    e[int(dur * SR):] *= np.linspace(1, 0, n - int(dur * SR))
    x = x * e
    if grit: x = lp(np.tanh(x * (1 + 4 * grit)), 900)
    return x * 0.5 * v

def epiano(note, dur, v=1.0):
    n = int((dur + 1.2) * SR); t = np.arange(n) / SR
    f = hz(note)
    idx = 1.6 * np.exp(-t * 3.5) + 0.15
    x = np.sin(2 * np.pi * f * t + idx * np.sin(2 * np.pi * f * t))
    x += 0.18 * np.sin(2 * np.pi * f * 7.02 * t) * np.exp(-t * 18)  # tine
    e = np.minimum(1, t / 0.004) * np.exp(-t * 1.0)
    rel = int(dur * SR); e[rel:] *= np.exp(-np.arange(n - rel) / SR * 6)
    x *= e * (1 + 0.12 * np.sin(2 * np.pi * 4.2 * t))
    return lp(x, 3500) * 0.16 * v

def koto(note, dur, v=1.0, bend=0.0):
    """Karplus-Strong plucked string, processed one period-block at a time."""
    n = int((dur + 1.5) * SR)
    f = hz(note); N = max(2, int(round(SR / f - 0.5)))  # the 2-tap average adds half a sample of delay
    y = np.zeros(n + N + 1)
    burst = rng.uniform(-1, 1, N); burst = burst - burst.mean()
    burst = np.convolve(burst, [0.6, 0.4], 'same')  # slightly darker pluck
    y[:N] = burst
    decay = 0.996 if note < 70 else 0.993
    i = N
    while i < n:
        j = min(n, i + N)
        prev = y[i - N:j - N]; prev2 = y[i - N - 1:j - N - 1] if i - N - 1 >= 0 else np.concatenate([[0], y[i - N:j - N - 1]])
        y[i:j] = decay * 0.5 * (prev + prev2)
        i = j
    y = y[:n]
    t = np.arange(n) / SR
    rel = int(dur * SR); e = np.ones(n); e[rel:] = np.exp(-np.arange(n - rel) / SR * 4)
    x = y * e
    x = x + 0.4 * hp(x, 2500) * np.exp(-t * 20)  # bright plectrum attack
    return fade(x, 0.001, 0.05) * 0.5 * v

def shaku(note, dur, v=1.0, slide=True):
    """Breathy end-blown flute: vibrato that opens up, a meri slide into the note."""
    n = int((dur + 0.25) * SR); t = np.arange(n) / SR
    f0 = hz(note)
    s = (1 - np.exp(-t * 14)) if slide else 1
    vib = 1 + 0.008 * np.sin(2 * np.pi * 5.2 * t) * np.minimum(1, t / 0.6)
    f = f0 * (2 ** (-1.2 / 12 * (1 - s))) * vib
    ph = 2 * np.pi * np.cumsum(f) / SR
    tone = np.sin(ph) + 0.22 * np.sin(2 * ph) + 0.08 * np.sin(3 * ph)
    breath = bp(rng.normal(0, 1, n), f0 * 1.5, min(f0 * 6, 12000)) * 0.35
    e = np.minimum(1, t / 0.09) * (0.85 + 0.15 * np.sin(2 * np.pi * 0.7 * t))
    rel = int(dur * SR); e[rel:] *= np.exp(-np.arange(n - rel) / SR * 14)
    chiff = bp(rng.normal(0, 1, n), 2000, 8000) * np.exp(-t * 30) * 0.3
    return (tone * e + breath * e + chiff) * 0.2 * v

# ---------------------------------------------------------------- mixing
class Track:
    def __init__(self, bpm, bars):
        self.bpm, self.bars = bpm, bars
        self.beat = 60.0 / bpm
        self.L = int(round(bars * 4 * self.beat * SR))
        self.bus = {k: np.zeros((self.L + 4 * SR, 2)) for k in ('drums', 'keys', 'lead', 'bass', 'fx')}
        self.swing = 0.56
    def t16(self, bar, step):  # time (s) of a swung 16th
        beat = step // 4; sub = step % 4
        off = [0, self.swing * 0.5, 0.5, 0.5 + self.swing * 0.5][sub]
        return (bar * 4 + beat + off) * self.beat
    def add(self, bus, x, t, pan=0.0, hum=0.004):
        t = t + rng.normal(0, hum) if hum else t
        i = int(max(0, t) * SR) % self.L
        n = min(len(x), self.bus[bus].shape[0] - i)
        l, r = np.cos((pan + 1) * np.pi / 4), np.sin((pan + 1) * np.pi / 4)
        self.bus[bus][i:i + n, 0] += x[:n] * l * 1.41
        self.bus[bus][i:i + n, 1] += x[:n] * r * 1.41

def circular(buf, L):
    out = buf[:L].copy(); k = L
    while k < buf.shape[0]:
        seg = buf[k:k + L]; out[:len(seg)] += seg; k += L
    return out

def ir(sec, damp, seed):
    r = np.random.default_rng(seed); n = int(sec * SR); t = np.arange(n) / SR
    x = r.normal(0, 1, n) * np.exp(-t * 6.9 / sec)
    x = lp(x, damp); x[: int(0.012 * SR)] = 0
    return x / np.sqrt(np.sum(x ** 2))

def reverb_circ(x, sec=2.2, damp=4500, mix=0.25):
    L = x.shape[0]; out = np.zeros_like(x)
    for c in range(2):
        tiled = np.concatenate([x[:, c], x[:, c]])
        w = fftconvolve(tiled, ir(sec, damp, 11 + c))[:2 * L + int(sec * SR)]
        w = circular(w[:, None], L)[:, 0]
        out[:, c] = w
    return x + out * mix

def master(tr, rev, bass_gain=1.0, fx_gain=1.0):
    L = tr.L
    b = {k: circular(v, L) for k, v in tr.bus.items()}
    # dusty drums: band-limit, gentle crush, a little room
    d = b['drums']
    d = np.stack([lp(hp(d[:, c], 35), 9000) for c in range(2)], 1)
    d = np.round(d * 2048) / 2048 * 0.5 + d * 0.5
    d = reverb_circ(d, 0.9, 5000, 0.12)
    # sidechain: keys and lead dip under each kick
    duck = np.ones(L)
    for kt in tr.kicks:
        i = int(kt * SR) % L; n = int(0.22 * SR); idx = (np.arange(n) + i) % L
        duck[idx] = np.minimum(duck[idx], 1 - 0.35 * np.exp(-np.arange(n) / SR * 14))
    keys = reverb_circ(b['keys'] * duck[:, None], rev, 4200, 0.35)
    lead = reverb_circ(b['lead'] * duck[:, None], rev + 0.6, 6000, 0.4)
    bs = np.stack([lp(b['bass'][:, c], 1600) for c in range(2)], 1)
    fx = b['fx']
    mix = d * 1.0 + keys * 0.9 + lead * 0.95 + bs * bass_gain + fx * fx_gain
    # tape: warm low-pass, slow wow, hiss + vinyl crackle
    t = np.arange(L) / SR
    hiss = lp(rng.normal(0, 1, (L, 2)), 6000, 1) * 0.004
    crack = np.zeros((L, 2)); k = rng.integers(0, L, int(L / SR * 9))
    crack[k, :] = rng.normal(0, 0.25, (len(k), 1)); crack = np.stack([bp(crack[:, c], 1500, 9000) for c in range(2)], 1)
    mix = np.stack([lp(mix[:, c], 11000) for c in range(2)], 1) + hiss + crack * 0.6
    # loudness-match every track (RMS target), then a soft limiter for peaks
    mix = mix * (10 ** (-14 / 20) / np.sqrt(np.mean(mix ** 2)))
    mix = np.tanh(mix * 1.3) / 1.3
    peak = np.max(np.abs(mix))
    if peak > 0.89: mix = mix / peak * 0.89
    return mix

# ---------------------------------------------------------------- arrangement helpers
def chord_notes(root, kind):
    iv = {'m9': [0, 3, 7, 10, 14], 'maj7': [0, 4, 7, 11], 'maj7s11': [0, 4, 7, 11, 18], 'm7': [0, 3, 7, 10], '7sus': [0, 5, 7, 10], 'phry': [0, 1, 7, 10]}[kind]
    return [root + i for i in iv]

def boom_bap(tr, bar, kick_steps=(0, 7, 10), fill=False, hard=False, vel=1.0):
    for s in kick_steps:
        t = tr.t16(bar, s); tr.add('drums', kick(vel * (0.95 if s else 1), hard), t, 0, 0.003); tr.kicks.append(t)
    for s in (4, 12):
        tr.add('drums', snare(vel), tr.t16(bar, s), 0.05, 0.005)
    for s in range(0, 16, 2):
        tr.add('drums', hat(vel * (0.9 if s % 4 == 0 else 0.65)), tr.t16(bar, s), 0.3)
    if fill:
        for s in (13, 14, 15): tr.add('drums', rim(0.8), tr.t16(bar, s), -0.2)
    elif rng.random() < 0.6:
        tr.add('drums', hat(0.4), tr.t16(bar, int(rng.choice([3, 7, 11, 15]))), 0.3)
    if bar % 4 == 3: tr.add('drums', hat(0.5, True), tr.t16(bar, 14), 0.35)

def keys_bar(tr, bar, root, kind, inv=0, beats=4, vel=1.0):
    ns = chord_notes(root, kind)
    for i, nt in enumerate(ns):
        tr.add('keys', epiano(nt + 12 * (inv and i < inv), beats * tr.beat * 0.92, vel * (1.0 - 0.08 * i)), tr.t16(bar, 0) + i * 0.012, -0.25 + 0.5 * i / len(ns), 0.002)

# ---------------------------------------------------------------- tracks
def ink_road():
    """Normal waves. 84 BPM, A minor with a Bb (Phrygian) colour; koto + shakuhachi."""
    tr = Track(84, 16); tr.kicks = []
    prog = [(57, 'm9'), (53, 'maj7'), (50, 'm9'), (46, 'maj7s11')]
    hira = [69, 71, 72, 76, 77, 81, 83, 84]  # A hirajoshi
    for bar in range(16):
        root, kind = prog[bar % 4]
        boom_bap(tr, bar, (0, 7, 10) if bar % 2 == 0 else (0, 3, 10), fill=(bar % 8 == 7))
        keys_bar(tr, bar, root, kind, inv=1 if bar % 8 >= 4 else 0, vel=0.9)
        bn = root - 12 if root > 45 else root
        tr.add('bass', bass(bn, tr.beat * 1.6), tr.t16(bar, 0), 0)
        tr.add('bass', bass(bn, tr.beat * 0.4, 0.8), tr.t16(bar, 7), 0)
        tr.add('bass', bass(bn + (7 if kind != 'maj7s11' else 4), tr.beat * 0.9, 0.85), tr.t16(bar, 10), 0)
        if bar < 8:   # A section: sparse koto answers
            if bar % 2 == 1:
                ph = [hira[i] for i in ([4, 3, 1] if bar % 4 == 1 else [5, 4, 3, 0])]
                for k, nt in enumerate(ph): tr.add('lead', koto(nt, tr.beat * 0.9, 0.9), tr.t16(bar, 8 + k * 2), 0.3)
        else:         # B section: koto melody + shakuhachi long tones
            mel = [[7, None, 6, 4, None, 3, 4, None], [3, None, 1, 0, None, 1, 3, None], [4, None, 5, 7, None, 6, 4, 3], [1, None, None, 0, None, None, None, None]][bar % 4]
            for k, ix in enumerate(mel):
                if ix is not None: tr.add('lead', koto(hira[ix] - 12, tr.beat * 0.8, 0.8), tr.t16(bar, k * 2), 0.35)
            if bar % 2 == 0:
                tr.add('lead', shaku([76, 72, 77, 69][(bar // 2) % 4], tr.beat * 3.2, 0.9), tr.t16(bar, 2), -0.3)
    return tr, 1.9

def willow_rain():
    """Alternate stage loop. 78 BPM, D dorian-ish, rolling koto arpeggios, softer drums."""
    tr = Track(78, 16); tr.kicks = []; tr.swing = 0.6
    prog = [(50, 'm9'), (55, '7sus'), (48, 'maj7'), (45, 'm7')]
    for bar in range(16):
        root, kind = prog[bar % 4]
        boom_bap(tr, bar, (0, 6, 9) if bar % 2 == 0 else (0, 10, 11), fill=(bar % 8 == 7), vel=0.85)
        keys_bar(tr, bar, root, kind, inv=1, vel=0.75)
        bn = root - 12 if root > 45 else root
        tr.add('bass', bass(bn, tr.beat * 2.5), tr.t16(bar, 0), 0)
        tr.add('bass', bass(bn + 12, tr.beat * 0.3, 0.6), tr.t16(bar, 11), 0)
        tr.add('bass', bass(bn + 7, tr.beat * 0.8, 0.8), tr.t16(bar, 12), 0)
        ns = chord_notes(root + 12, kind)
        arp = ns + ns[-2:0:-1]
        for k in range(8 if bar >= 4 else 4):
            nt = arp[k % len(arp)] + (12 if bar >= 12 and k % 4 == 3 else 0)
            tr.add('lead', koto(nt, tr.beat * 0.5, 0.55 + 0.15 * (k % 2 == 0)), tr.t16(bar, k * 2 if bar >= 4 else 8 + k * 2), 0.25 * (1 if k % 2 else -1))
        if bar in (8, 10, 12, 14):
            tr.add('lead', shaku([74, 72, 69, 67][(bar - 8) // 2] + 0, tr.beat * 3.5, 0.75), tr.t16(bar, 4), -0.35)
    return tr, 2.3

def oni_drums():
    """Boss waves. 92 BPM, E Phrygian: taiko on the downbeats, gritty bass, shakuhachi cries."""
    tr = Track(92, 16); tr.kicks = []; tr.swing = 0.53
    prog = [(52, 'phry'), (53, 'maj7'), (52, 'phry'), (50, 'm7')]
    for bar in range(16):
        root, kind = prog[bar % 4]
        boom_bap(tr, bar, (0, 3, 8, 10) if bar % 2 == 0 else (0, 6, 10, 14), fill=(bar % 4 == 3), hard=True, vel=1.05)
        tr.add('fx', taiko(1.0, 58), tr.t16(bar, 0), -0.1, 0.002)
        if bar % 2 == 1: tr.add('fx', taiko(0.7, 70), tr.t16(bar, 12), 0.2)
        if bar % 4 == 3:
            for s in (8, 10, 12, 13, 14, 15): tr.add('fx', taiko(0.45 + 0.05 * (s - 8), 78), tr.t16(bar, s), 0.15)
        keys_bar(tr, bar, root, kind, vel=0.55)
        bn = root - 12
        for s, d in ((0, 0.7), (3, 0.4), (6, 0.4), (8, 0.7), (11, 0.4), (14, 0.4)):
            tr.add('bass', bass(bn + (1 if s == 14 and bar % 2 else 0), tr.beat * d, 0.95, grit=0.7), tr.t16(bar, s), 0)
        # koto ostinato: E F B E pattern, staccato
        ost = [64, 65, 71, 64, 76, 71, 65, 64]
        for k, nt in enumerate(ost): tr.add('lead', koto(nt, tr.beat * 0.25, 0.6), tr.t16(bar, k * 2), 0.3 * (1 if k % 2 else -1))
        if bar >= 8 and bar % 2 == 0:
            tr.add('lead', shaku([83, 81, 77, 76][(bar - 8) // 2], tr.beat * 2.6, 1.0), tr.t16(bar, 1), -0.25)
    tr.mix = dict(bass_gain=0.6, fx_gain=0.75)
    return tr, 1.6

def write_wav(path, x):
    import wave
    y = (np.clip(x, -1, 1) * 32767).astype('<i2')
    with wave.open(path, 'wb') as w:
        w.setnchannels(2); w.setsampwidth(2); w.setframerate(SR); w.writeframes(y.tobytes())

if __name__ == '__main__':
    out = sys.argv[1] if len(sys.argv) > 1 else '/tmp/music'
    os.makedirs(out, exist_ok=True)
    meta = {}
    for name, fn in (('ink-road', ink_road), ('willow-rain', willow_rain), ('oni-drums', oni_drums)):
        tr, rev = fn()
        loop = master(tr, rev, **getattr(tr, 'mix', {}))
        p = int(PAD * SR)
        padded = np.concatenate([loop[-p:], loop, loop[:p]])
        write_wav(f'{out}/{name}.wav', padded)
        meta[name] = {'bpm': tr.bpm, 'loopStart': PAD, 'loopLength': tr.L / SR, 'loopSamples': tr.L, 'rate': SR}
        print(name, f'{tr.L / SR:.2f}s loop')
    json.dump(meta, open(f'{out}/loops.json', 'w'), indent=1)
